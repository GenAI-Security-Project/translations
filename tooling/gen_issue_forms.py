#!/usr/bin/env python3
"""Generate the intake issue forms and the site's language list.

GitHub issue-form dropdowns are fixed lists inside the form's YAML, so the
lists that change -- the registered documents (registry.yaml) and the
language catalogue (tooling/languages.json) -- are written into the forms
by this script rather than by hand:

  .github/ISSUE_TEMPLATE/onboard-document.yml  new document only (+ file)
  .github/ISSUE_TEMPLATE/add-language.yml      existing document, new languages
  docs/js/languages.js                         the Status page's picker list

.github/workflows/sync-issue-forms.yml runs it on every push to main that
touches registry.yaml, languages.json or this script, and commits any
change. Run it by hand after editing languages.json; `--check` exits 1 if
the generated files are out of date.

Dropdown options are shown as "Japanese — 日本語 [ja-JP]"; the issue body
repeats the chosen labels, and parse_onboarding_issue.py reads the codes
back out of the square brackets.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
LANGUAGES = ROOT / "tooling" / "languages.json"
REGISTRY = ROOT / "registry.yaml"
ONBOARD = ROOT / ".github" / "ISSUE_TEMPLATE" / "onboard-document.yml"
ADD_LANGUAGE = ROOT / ".github" / "ISSUE_TEMPLATE" / "add-language.yml"
LANGUAGES_JS = ROOT / "docs" / "js" / "languages.js"

HEADER = "# GENERATED by tooling/gen_issue_forms.py -- edit that script (or\n# tooling/languages.json / registry.yaml) instead, then run it.\n"
TEMPLATES = ["green-template", "blue-template", "yellow-template"]
STATUS_URL = "https://genai-security-project.github.io/translations/status.html"


def q(s: str) -> str:
    """A YAML-safe quoted scalar (JSON strings are valid YAML)."""
    return json.dumps(s, ensure_ascii=False)


def language_label(lang: dict) -> str:
    return f"{lang['name']} — {lang['native']} [{lang['code']}]"


def options(items, indent: int = 8) -> str:
    pad = " " * indent
    return "\n".join(f"{pad}- {q(i)}" for i in items)


def onboard_form(languages) -> str:
    return HEADER + f"""name: Onboard a new document
description: "Translations managers only: submit a finished English document to be translated."
title: "Onboard: "
labels: ["onboarding"]
body:
  - type: markdown
    attributes:
      value: |
        For a **new document** only. To add languages to a document that's already here, use the
        **Add languages to a document** form (or **+ Add languages** on the
        [Status page]({STATUS_URL})).

        Only **translations managers** can use this (the `translations-managers` team, Maintain on
        this repo, or an org owner); anyone else's request is declined with a comment. The result is
        an onboarding pull request, linked here in a comment; merging it starts a machine-drafted
        translation of each language automatically.
  - type: textarea
    id: source_file
    attributes:
      label: Source file
      description: "Drag the finished English **.pdf** or **.docx** into this box (one file). Its file name becomes the document id, so name it well, e.g. `OWASP-Top-10-for-LLM-Applications-2026.pdf`."
      placeholder: Drop the .pdf or .docx here
    validations:
      required: true
  - type: input
    id: version
    attributes:
      label: Version
      placeholder: "2026.12.6"
    validations:
      required: true
  - type: dropdown
    id: locales
    attributes:
      label: Languages to translate into
      description: Choose one or more.
      multiple: true
      options:
{options(language_label(l) for l in languages)}
    validations:
      required: true
  - type: input
    id: other_locales
    attributes:
      label: Other language codes (optional)
      description: Only for languages missing from the list above. Comma-separated BCP-47 codes.
      placeholder: "mn-MN"
  - type: dropdown
    id: template
    attributes:
      label: Layout template
      options:
{options(TEMPLATES)}
      default: 0
    validations:
      required: true
  - type: input
    id: source_repo
    attributes:
      label: English source repository (optional)
      placeholder: "GenAI-Security-Project/Agentic-Top-10"
  - type: input
    id: source_path
    attributes:
      label: Path in that repository (optional)
      placeholder: "_source/"
  - type: input
    id: owners
    attributes:
      label: Document owners (optional)
      description: Comma-separated GitHub usernames. Defaults to you.
  - type: checkboxes
    id: public_ack
    attributes:
      label: Public file
      options:
        - label: I understand that this repository is public, so the attached file can be downloaded by anyone.
          required: true
"""


def add_language_form(languages, assets) -> str:
    doc_options = options(assets) if assets else options(["(no documents registered yet)"])
    return HEADER + f"""name: Add languages to a document
description: "Translations managers only: translate an already-onboarded document into more languages. Drafting starts automatically."
title: "Add languages"
labels: ["add-language"]
body:
  - type: markdown
    attributes:
      value: |
        Pick the document and the languages to add. Languages the document already has are skipped
        (the [Status page]({STATUS_URL}) shows what each document has).

        Only **translations managers** can use this (the `translations-managers` team, Maintain on
        this repo, or an org owner); anyone else's request is declined with a comment. When you
        press **Create**, the languages are registered and a machine-drafted translation of each
        starts, one at a time. Each draft opens its own pull request for review, linked here.
  - type: dropdown
    id: asset
    attributes:
      label: Document
      options:
{doc_options}
    validations:
      required: true
  - type: dropdown
    id: locales
    attributes:
      label: Languages to add
      description: Choose one or more.
      multiple: true
      options:
{options(language_label(l) for l in languages)}
  - type: input
    id: other_locales
    attributes:
      label: Other language codes (optional)
      description: Only for languages missing from the list above. Comma-separated BCP-47 codes.
      placeholder: "mn-MN"
"""


def languages_js(languages) -> str:
    rows = "\n".join(f"  [{q(l['code'])}, {q(l['name'])}, {q(l['native'])}]," for l in languages)
    return f"""// GENERATED by tooling/gen_issue_forms.py from tooling/languages.json --
// edit that file and re-run the script. The same list feeds the issue
// forms' language dropdowns. Rows: [BCP-47 code, English name, native name].
const LANGUAGES = [
{rows}
];

const LANGUAGE_NAMES = Object.fromEntries(LANGUAGES.map(([code, name]) => [code, name]));

// The issue forms' dropdown label for a code, e.g. "Japanese — 日本語 [ja-JP]".
function languageOptionLabel(code) {{
  const row = LANGUAGES.find(([c]) => c === code);
  return row ? `${{row[1]}} — ${{row[2]}} [${{row[0]}}]` : null;
}}
"""


def main() -> None:
    languages = sorted(json.loads(LANGUAGES.read_text()), key=lambda l: l["name"])
    registry = yaml.load(REGISTRY.read_text(), Loader=yaml.BaseLoader) or {}
    assets = sorted((registry.get("assets") or {}).keys())
    outputs = {
        ONBOARD: onboard_form(languages),
        ADD_LANGUAGE: add_language_form(languages, assets),
        LANGUAGES_JS: languages_js(languages),
    }
    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text() != text]
    if "--check" in sys.argv:
        for p in stale:
            print(f"out of date: {p.relative_to(ROOT)}")
        sys.exit(1 if stale else 0)
    for p in stale:
        p.write_text(outputs[p])
        print(f"wrote {p.relative_to(ROOT)}")
    if not stale:
        print("issue forms and language list already up to date")


if __name__ == "__main__":
    main()
